/**
 * Formats province group name according to user configuration
 */
export function formatProvinceGroupName(
  detectedProvince: string,
  format: "raw" | "suffix_local" | "suffix_province" | "suffix_channel" | string = "raw",
  existingGroupNames: string[] = []
): string {
  if (!detectedProvince) return "其它频道";

  if (detectedProvince === "香港" || detectedProvince === "澳门" || detectedProvince === "台湾") {
    return "港澳台";
  }

  // 1. Check if an existing group already represents this province (avoid duplicates)
  const possibleVariants = [
    detectedProvince,
    `${detectedProvince}地方`,
    `${detectedProvince}省`,
    `${detectedProvince}市`,
    `${detectedProvince}频道`
  ];

  for (const variant of possibleVariants) {
    if (existingGroupNames.includes(variant)) {
      return variant;
    }
  }

  // 2. Format according to selected naming style
  switch (format) {
    case "suffix_local":
      return `${detectedProvince}地方`;
    case "suffix_province":
      if (["北京", "上海", "天津", "重庆"].includes(detectedProvince)) {
        return `${detectedProvince}市`;
      }
      return `${detectedProvince}省`;
    case "suffix_channel":
      return `${detectedProvince}频道`;
    case "raw":
    default:
      return detectedProvince;
  }
}

/**
 * Determine Smart Target Group(s)
 */
export function determineSmartTargetGroups(
  channelName: string,
  detectedProvince: string,
  options: {
    groupingMode?: "smart" | "province_only" | "keep_existing" | string;
    provinceNameFormat?: "raw" | "suffix_local" | "suffix_province" | "suffix_channel" | string;
    allowMultiGroup?: boolean;
  } = {},
  existingGroupNames: string[] = []
): string[] {
  const mode = options.groupingMode || "smart";
  const format = options.provinceNameFormat || "raw";
  const allowMultiGroup = options.allowMultiGroup !== false;
  const upper = channelName.toUpperCase();

  // Mode: Pure Province-Only Grouping
  if (mode === "province_only") {
    if (detectedProvince) {
      return [formatProvinceGroupName(detectedProvince, format, existingGroupNames)];
    }
    return ["其它频道"];
  }

  const matches: string[] = [];

  // 1. CCTV / 央视
  const isCctv = /^CCTV/i.test(upper) || upper.includes("央视") || upper.includes("CGTN") || upper.includes("CETV");
  if (isCctv) {
    matches.push("央视频道");
  }

  // 2. Satellite TV / 卫视
  const isSat = channelName.includes("卫视");
  if (isSat) {
    matches.push("卫视频道");
  }

  // 3. 4K/8K
  if (upper.includes("4K") || upper.includes("8K") || upper.includes("超高清") || upper.includes("UHD")) {
    matches.push("4K超清");
  }

  // 4. HK / Macao / Taiwan
  const isHkMoTw = /翡翠|明珠|TVB|凤凰|澳视|华视|台视|中视|三立|东森|HBO|星空|年代|纬来|靖天|龙祥|ViuTV|HOY/i.test(channelName) ||
    detectedProvince === "香港" || detectedProvince === "澳门" || detectedProvince === "台湾";
  if (isHkMoTw) {
    matches.push("港澳台");
  }

  // 5. Sports
  if (/体育|五星|风云足球|高尔夫|极速汽车|先锋乒羽/i.test(channelName)) {
    matches.push("体育频道");
  }

  // 6. Movies / Cinema / Drama / Anime
  if (/影院|电影|剧场|动作|喜剧|动画|少儿|卡通|纪录片|纪实|iHOT|CHC|欢笑剧场|都市剧场|七彩戏剧/i.test(channelName)) {
    matches.push("影视频道");
  }

  // 7. Provincial / Local Stations
  // If it is detected as a province and is NOT purely a national satellite or HK/Macau/Taiwan,
  // or if allowMultiGroup is enabled, add provincial group
  if (detectedProvince && !matches.includes("港澳台")) {
    const provGroup = formatProvinceGroupName(detectedProvince, format, existingGroupNames);
    if (!matches.includes(provGroup)) {
      matches.push(provGroup);
    }
  }

  if (matches.length === 0) {
    matches.push("其它频道");
  }

  if (!allowMultiGroup) {
    return [matches[0]];
  }

  return matches;
}

/**
 * Clean & Normalize Channel Name for Smart Organize
 */
export function cleanChannelNameForSmartOrganize(
  originalName: string,
  options: {
    stripResolution?: boolean;
    extractIspAndProvince?: boolean;
    normalizeCctv?: boolean;
    normalizeSatTv?: boolean;
  } = {},
  stripBitrateFn?: (name: string) => string,
  normalizeChannelNameFn?: (name: string) => string
): string {
  if (!originalName) return "";
  let name = originalName.trim();

  if (options.stripResolution !== false) {
    if (stripBitrateFn) {
      name = stripBitrateFn(name);
    } else {
      name = stripNoiseForDetection(name);
    }
  }

  if (options.extractIspAndProvince !== false) {
    name = name.replace(/(?:\s+|-|_)*(?:移动|电信|联通|广电|华数|歌华|BGP|内网|组播|单播)+(?:\s+|-|_)*/gi, " ");
  }

  if (options.normalizeCctv !== false && /^cctv/i.test(name.trim())) {
    const normKey = normalizeChannelNameFn ? normalizeChannelNameFn(name) : name.toLowerCase().replace(/[-_.\s]+/g, "");
    if (STANDARD_CCTV_NAME_MAP[normKey]) {
      return STANDARD_CCTV_NAME_MAP[normKey];
    }
  }

  if (options.normalizeSatTv !== false && name.includes("卫视")) {
    const matchSat = name.match(/([\u4e00-\u9fa5]{2,6}卫视)/);
    if (matchSat) {
      return matchSat[1];
    }
  }

  name = name.replace(/^[\s\-_:,，;；]+|[\s\-_:,，;；]+$/g, "").trim();
  return name || originalName;
}
