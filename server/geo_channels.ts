// Sorted list of all search terms (longer terms first to prevent partial collision)
const ALL_SEARCH_TERMS: { term: string; province: string }[] = (() => {
  const map = new Map<string, string>();

  // 1. Regional brands (highest specificity)
  for (const [k, v] of Object.entries(REGIONAL_TV_BRANDS)) {
    map.set(k, v);
  }

  // 2. City / County / District
  for (const [k, v] of Object.entries(CITY_TO_PROVINCE)) {
    map.set(k, v);
    // Also include with '市' / '县' / '区' if not already present
    if (k.length === 2 && !map.has(k + "市")) map.set(k + "市", v);
    if (k.length === 2 && !map.has(k + "县")) map.set(k + "县", v);
  }

  // 3. Full provinces
  for (const p of PROVINCES_LIST) {
    map.set(p, p);
    if (!map.has(p + "省")) map.set(p + "省", p);
    if (!map.has(p + "市")) map.set(p + "市", p);
    if (!map.has(p + "卫视")) map.set(p + "卫视", p);
  }

  // Convert to array and sort by length descending
  const list: { term: string; province: string }[] = [];
  for (const [term, province] of map.entries()) {
    list.push({ term, province });
  }

  list.sort((a, b) => b.term.length - a.term.length);
  return list;
})();

/**
 * Strips resolution, bitrate, brackets, codec, and network indicators for clean matching
 */
export function stripNoiseForDetection(raw: string): string {
  if (!raw) return "";
  let s = raw;
  // Strip brackets and content like [1080P], (HEVC), [IPV6], etc.
  s = s.replace(/\[[^\]]*\]|\([^\)]*\)|（[^）]*）|【[^】]*】/g, " ");
  // Strip common technical tags
  s = s.replace(/(?:4K|8K|1080P|720P|HD|FHD|UHD|SD|HEVC|H264|H265|IPV6|IPV4|60FPS|50FPS|5\.1)/gi, " ");
  // Strip common network tags
  s = s.replace(/(?:电信|联通|移动|广电|华数|歌华|长宽|BGP|内网|组播|单播)/gi, " ");
  return s.trim();
}

/**
 * Intelligent Province & ISP Detection from Channel Name and Stream URLs
 */
export function detectProvinceAndIspFromName(text: string, streamUrls: string[] = []): { detectedProvince: string; detectedIsp: string } {
  let detectedProvince = "";
  let detectedIsp = "";

  if (!text) return { detectedProvince, detectedIsp };

  // 1. Detect ISP
  if (/电信|ctc|telecom|189\.cn/i.test(text)) detectedIsp = "电信";
  else if (/联通|cnc|unicom|10010/i.test(text)) detectedIsp = "联通";
  else if (/移动|cmcc|chinamobile|10086/i.test(text)) detectedIsp = "移动";
  else if (/广电|华数|歌华|cbn/i.test(text)) detectedIsp = "广电";

  // Check URLs for ISP if text did not indicate
  if (!detectedIsp && streamUrls && streamUrls.length > 0) {
    const urlText = streamUrls.join(" ");
    if (/telecom|189\.cn/i.test(urlText)) detectedIsp = "电信";
    else if (/unicom|10010/i.test(urlText)) detectedIsp = "联通";
    else if (/chinamobile|10086/i.test(urlText)) detectedIsp = "移动";
    else if (/cbn|wasu|gehua/i.test(urlText)) detectedIsp = "广电";
  }

  // 2. Detect Province from Channel Name
  const cleanName = stripNoiseForDetection(text);

  // Exact matching against longest terms first
  for (const item of ALL_SEARCH_TERMS) {
    if (cleanName.includes(item.term) || text.includes(item.term)) {
      detectedProvince = item.province;
      break;
    }
  }

  // 3. Fallback: Check Channel Suffix Pattern (e.g. "顺德新闻", "义乌综合", "常熟一套", "江阴都市")
  if (!detectedProvince) {
    const suffixRegex = /([\u4e00-\u9fa5]{2,6})(?:新闻综合|新闻|综合|都市|生活|影视|科教|文体|文艺|公共|法治|经济|少儿|农科|房产|交通|导视|资讯|图文|融媒|一套|二套|三套|四套|五套|六套|七套|八套|1套|2套|3套|4套|5套|6套|7套|8套|台|频道)/;
    const match = cleanName.match(suffixRegex);
    if (match && match[1]) {
      const prefix = match[1];
      if (CITY_TO_PROVINCE[prefix]) {
        detectedProvince = CITY_TO_PROVINCE[prefix];
      }
    }
  }

  // 4. Fallback: Check Stream URLs for provincial/city pinyin or domain keywords
  if (!detectedProvince && streamUrls && streamUrls.length > 0) {
    const combinedUrl = streamUrls.join(" ").toLowerCase();
    for (const [pinyin, prov] of Object.entries(PROVINCIAL_PINYIN_MAP)) {
      // Look for boundary-separated pinyin in URL (e.g. "gd.", "gd-", "/gd/", "guangdong", "hunan.")
      const pinyinPattern = new RegExp(`[/._-]${pinyin}[/._-]`, "i");
      if (pinyinPattern.test(combinedUrl)) {
        detectedProvince = prov;
        break;
      }
    }
  }

  return { detectedProvince, detectedIsp };
}

